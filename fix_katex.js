  fixed = fixed.replace(/(?<![\$])d_1(?![\$])/g, '$d_1$');
  
  // Fix fractions
  // Find \frac{...}{...} that is not inside $ or $$
  // Using a regex for simple \frac{}{}
  fixed = fixed.replace(/(?<![\$])\\frac\{[^{}]*\}\{[^{}]*\}(?![\$])/g, '$$&$');
  
