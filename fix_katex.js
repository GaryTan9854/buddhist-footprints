  fixed = fixed.replace(/(?<![\$])f'\(x\)(?![\$])/g, "$f'(x)$");
  fixed = fixed.replace(/(?<![\$])f\(t\)(?![\$])/g, '$f(t)$');
  fixed = fixed.replace(/(?<![\$])f'\(t\)(?![\$])/g, "$f'(t)$");
  fixed = fixed.replace(/(?<![\$])f\(t\s*\+\s*\\Delta\s*t\)(?![\$])/g, '$f(t + \\Delta t)$');
  fixed = fixed.replace(/(?<![\$])\\Delta\s*t\s*\\to\s*0(?![\$])/g, '$\\Delta t \\to 0$');
  fixed = fixed.replace(/(?<![\$])t\s*\\to\s*0(?![\$])/g, '$t \\to 0$');
